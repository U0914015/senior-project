--             10週實驗期）。⚠️ 這個家族要教師後台先設定該班的「📅 研究開始日」才算得出來，
--             沒設定的班級這個家族永遠不會觸發，不是 bug
--   絕地反攻   小隊全體「單場正確率比上一場進步≥20個百分點」次數加總（3/8/16/30 次）
--   人人有功練 小組裡「個人系統分達到某個門檻」的人數，門檻跟人數要求一起往上升
--             （≥2人達50分 / ≥3人達150分 / 全員達300分 / 全員達800分）——傳說級要求
--             全組每個人都自己練到800分，不能只靠一個人扛，直接對應 pptx 依變項裡「社會互動
--             均衡度」關心的「避免少數人主導、內向者邊緣化」
